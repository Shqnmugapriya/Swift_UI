//Int
var age: Int = 20
// print(age)
print("Age : \(age)")

// Double
var price: Double = 8.42
// print(price)
print("Price : \(price)")

// Float
var weight: Float = 55.5
// print(weight)
print("Weight : \(weight)")

//String
var name: String = "Priya"
// print(name)
print("Name : \(name)")

// Character
var grade: Character = "A"
// print(grade)
print("Grade : \(grade)")

//Bool
var isStudent: Bool = true
// print(isStudent)
print("Is Student : \(isStudent)")

//Array
var marks: [Int] = [80, 90, 75]
// print(marks)
print("Marks : \(marks)")

//Set
var numbers: Set<Int> = [10, 20, 30]
// print(numbers)
print("Numbers : \(numbers)")

//Dictionary
var student: [String: Int] = ["Priya": 90, "Nandhini": 85]
// print(student["Priya"]!)
print("Priya's Marks : \(student["Priya"]!)")
print("Nandhini's Marks : \(student["Nandhini"]!)")